package gmath

func Up() Vector2 {
	return Vec2(0.0, 1.0)
}

func Down() Vector2 {
	return Vec2(0.0, -1.0)
}

func Right() Vector2 {
	return Vec2(1.0, 0.0)
}

func Left() Vector2 {
	return Vec2(-1.0, 0.0)
}

func Zero() Vector2 {
	return Vec2(0.0, 0.0)
}

func One() Vector2 {
	return Vec2(1.0, 1.0)
}

func NegOne() Vector2 {
	return Vec2(-1.0, -1.0)
}
