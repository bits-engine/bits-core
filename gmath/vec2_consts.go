package gmath

func Up2() Vector2 {
	return Vec2(0.0, 1.0)
}

func Down2() Vector2 {
	return Vec2(0.0, -1.0)
}

func Right2() Vector2 {
	return Vec2(1.0, 0.0)
}

func Left2() Vector2 {
	return Vec2(-1.0, 0.0)
}

func Zero2() Vector2 {
	return Vec2(0.0, 0.0)
}

func One2() Vector2 {
	return Vec2(1.0, 1.0)
}

func NegOne2() Vector2 {
	return Vec2(-1.0, -1.0)
}
